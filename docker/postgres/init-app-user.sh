#!/usr/bin/env bash
set -e

psql -v ON_ERROR_STOP=1 --username admin --dbname "$POSTGRES_DB" <<-EOSQL
	CREATE USER app WITH PASSWORD '$POSTGRES_APP_PASSWORD';
	ALTER SCHEMA public OWNER TO app;

  CREATE USER grafana WITH PASSWORD '$POSTGRES_GRAFANA_PASSWORD';
  ALTER DEFAULT PRIVILEGES FOR ROLE app IN SCHEMA public GRANT SELECT ON TABLES TO grafana;
EOSQL